"""Write the header with the agent hash that the wrapper embeds (ТЗ §4 step 4).

Windows: signing-invariant PE hash, identical to mebet::win::pe_image_hash
(src/windows/shared/pe_hash.cpp), so the value survives SignPath signing.
Linux/macOS: plain SHA-256 of the shared library.

Usage: agent_hash.py --mode pe|plain --file <agent> --name <file name> --out <header>
"""
import argparse
import hashlib
import struct
import sys


def pe_image_hash(data):
    if data[:2] != b"MZ":
        raise ValueError("not an MZ file")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("no PE signature")
    fh = pe + 4
    sections, = struct.unpack_from("<H", data, fh + 2)
    opt_size, = struct.unpack_from("<H", data, fh + 16)
    opt = fh + 20
    magic, = struct.unpack_from("<H", data, opt)
    if magic == 0x10B:
        datadir = opt + 96
    elif magic == 0x20B:
        datadir = opt + 112
    else:
        raise ValueError("unknown optional header magic")
    checksum = opt + 64
    certdir = datadir + 4 * 8
    section_table = opt + opt_size
    size_of_headers, = struct.unpack_from("<I", data, opt + 60)
    end = size_of_headers
    for i in range(sections):
        s = section_table + i * 40
        raw_size, raw_ptr = struct.unpack_from("<II", data, s + 16)
        if raw_size and raw_ptr + raw_size > end:
            end = raw_ptr + raw_size
    if end > len(data):
        raise ValueError("sections run past the end of the file")
    h = hashlib.sha256()
    h.update(data[:checksum])
    h.update(data[checksum + 4:certdir])
    h.update(data[certdir + 8:end])
    return h.digest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", required=True, choices=("pe", "plain"))
    ap.add_argument("--file", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    with open(a.file, "rb") as fh:
        data = fh.read()
    digest = pe_image_hash(data) if a.mode == "pe" else hashlib.sha256(data).digest()
    text = ("// Generated by tools/agent_hash.py after the agent was linked. Do not edit.\n"
            "#pragma once\n"
            "namespace mebet::generated {\n"
            "inline constexpr unsigned char kAgentHash[32] = { %s };\n"
            "inline constexpr const char* kAgentHashMode = \"%s\";\n"
            "inline constexpr const wchar_t* kAgentFileNameW = L\"%s\";\n"
            "inline constexpr const char* kAgentFileName = \"%s\";\n"
            "}  // namespace mebet::generated\n") % (
        ", ".join("0x%02x" % b for b in digest), a.mode, a.name, a.name)
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("agent_hash: %s %s" % (a.name, digest.hex()), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
